% OFM-Urban source code
%
% Entry points and results
%   ofm_urban          - Run a configured simulation and save each step.
%   read_ofm_series    - Read point series from step snapshots.
%   visualize          - Plot an inundation grid (Mapping Toolbox).
%
% Surface and channel routing
%   explicit           - Adaptive explicit diffusive-wave solver (TSTP2D=2).
%   overland           - Sequential routing scheme (TSTP2D=1).
%   diffusive_face     - Shared Manning transfers and original roof outlets.
%   chnroutin          - Channel link transfers.
%   cdepth             - Channel volume-to-depth conversion.
%   cflow              - Channel discharge.
%   qoutlet            - Surface outlet discharge.
%   qnode              - Free inlet discharge.
%   qmanhole           - Surface-to-sewer exchange.
%
% Hydrology and forcing
%   sample_forcing     - Sample native rainfall, weather and boundary records.
%   processing         - Batch resampling utility for preprocessing.
%   laivariant         - Seasonal LAI utility for preprocessing.
%   rainfest           - Apply gauge or gridded rainfall to a cell.
%   infiltration       - Green-Ampt infiltration.
%   runoffsimp         - Conceptual runoff reservoirs.
%   intercsnow         - Canopy interception, snowmelt and evaporation.
%   evapotrans         - Energy-balance evapotranspiration.
%   coordinate         - Coordinate conversion for evapotranspiration.
%   common             - Shared physical constants (script).
%   modswfip           - Read the optional soil-water model parameters.
%   soilground         - Optional SVAT soil-water model.
%
% Sewer coupling
%   build_swmm         - Compile the pinned EPA SWMM engine and MEX adapter.
%   prepare_swmm_input - Parse topology and prepare one startup input.
%   drainage           - Persistent SWMM session with direct array exchange.
%   swmm_live          - Compiled in-memory gateway (generated by build_swmm).
%
% The gateway source is in native/; EPA engine sources are in third_party/swmm/.
% The startup network and optional engine diagnostics belong in the run folder.

